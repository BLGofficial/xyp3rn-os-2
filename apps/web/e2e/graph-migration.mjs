import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { runInNewContext } from 'node:vm';
import { buildGraph } from '../../../galaxy/viewer/build-graph.js';
import { layoutGraph } from '../../../galaxy/viewer/graph-layout.js';

const base = process.env.GRAPH_URL || 'http://127.0.0.1:4700';
const out = 'docs/graph-migration';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.XYP_CHROMIUM || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const results = { scope: 'Live local Galaxy server; real indexed notes. No provider calls, microphone or workflow mutations.', checks: [], errors: [], resources: {} };
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
page.on('pageerror', e => results.errors.push(e.message));
await page.route('**/*', route => route.request().method() === 'GET' ? route.continue() : route.abort());
const check = (name, ok) => { assert.ok(ok, name); results.checks.push(name); };
const inspect = () => page.evaluate(() => window.graphView.inspect());
async function boot(url) {
  await page.goto(url);
  await page.waitForFunction(() => window.graphView && !document.body.classList.contains('booting'), { timeout: 25000 });
}
async function idle() { await page.waitForFunction(() => !window.graphView.inspect().animating); }
try {
  const sourceContext = {};
  const indexedResponse = await page.request.get(`${base}/graph-data.js`);
  runInNewContext((await indexedResponse.text()) + ';this.source=GRAPH', sourceContext);
  const expectedGraph = buildGraph(sourceContext.source);
  results.input = { notes: sourceContext.source.nodes.length, nodes: expectedGraph.nodes.length, edges: expectedGraph.edges.length, isolatedNotes: expectedGraph.isolated.length };
  results.runtime = { node: process.version, chromium: browser.version() };
  await boot(`${base}/?view=graph&mute=1`);
  await idle();
  const initial = await inspect();
  check('Every indexed note and source-backed group is rendered', initial.nodes.length === expectedGraph.nodes.length && initial.nodes.filter(n => n.kind !== 'cluster').length === sourceContext.source.nodes.length);
  check('Every edge resolves to real graph entities', initial.edges.length === expectedGraph.edges.length && initial.edges.every(e => initial.nodes.some(n => n.id === e.source) && initial.nodes.some(n => n.id === e.target)));
  results.layoutMs = initial.layoutMs;
  results.resources.graph = await page.evaluate(() => performance.getEntriesByType('resource').map(e => ({ name: e.name, bytes: e.encodedBodySize, transferred: e.transferSize })));
  check('Graph loads without WebGL/CDN graph runtimes', !results.resources.graph.some(e => /3d-force-graph|three@/.test(e.name)));
  await page.screenshot({ path: `${out}/graph-desktop.png` });
  const layout = initial.nodes.map(({ id, x, y }) => ({ id, x, y }));
  check('Browser worker layout matches Node headless layout', JSON.stringify(layout) === JSON.stringify(layoutGraph(expectedGraph)));
  await page.reload(); await page.waitForFunction(() => window.graphView && !document.body.classList.contains('booting')); await idle();
  check('Identical coordinates across page reloads', JSON.stringify((await inspect()).nodes.map(({ id, x, y }) => ({ id, x, y }))) === JSON.stringify(layout));
  await page.getByRole('button', { name: 'Browse nodes', exact: true }).click();
  check('Every node has an accessible browse button', await page.locator('#graph-picker li button').count() === expectedGraph.nodes.length);
  await page.getByRole('searchbox', { name: 'Search graph nodes' }).fill('README.md');
  const choice = page.locator('#graph-picker li button').filter({ hasText: 'xyp3rn-os-2-engine' }).first();
  await choice.click(); await idle();
  let selected = await inspect();
  check('Real source note opens shared inspector', (await page.locator('#note-path').innerText()) === 'README.md' && selected.selected === 'note:README.md');
  check('Selection encoded by path in URL', new URL(page.url()).searchParams.get('note') === 'README.md');
  await page.getByRole('searchbox', { name: 'Search graph nodes' }).press('Escape');
  await page.reload(); await page.waitForFunction(() => window.graphView && !document.body.classList.contains('booting')); await idle();
  const restored = await inspect();
  check('Selection and camera survive reload', restored.selected === selected.selected && ['x', 'y', 'k'].every(k => Math.abs(restored.camera[k] - selected.camera[k]) < .01));
  await page.screenshot({ path: `${out}/graph-note.png` });
  await page.locator('#close').click(); await page.getByRole('button', { name: 'Fit graph', exact: true }).click(); await idle();
  await page.locator('#tab-groups').click();
  await page.locator('#legend button[data-group="root"]').click(); await idle();
  check('Group filter persisted', new URL(page.url()).searchParams.get('group') === 'root');
  await page.reload(); await page.waitForFunction(() => window.graphView && !document.body.classList.contains('booting')); await idle();
  check('Group restored after reload', (await inspect()).selected === 'group:root');
  await page.getByRole('button', { name: 'Fit graph', exact: true }).click(); await idle();
  await page.locator('#nav button[data-domain="CORE"]').click(); await idle();
  check('Domain filter persisted', new URL(page.url()).searchParams.get('domain') === 'CORE');
  await page.reload(); await page.waitForFunction(() => window.graphView && !document.body.classList.contains('booting')); await idle();
  check('Domain restored after reload', (await inspect()).highlighted.length > 0 && await page.locator('#nav button[data-domain="CORE"]').getAttribute('aria-pressed') === 'true');
  await page.getByRole('button', { name: 'Fit graph', exact: true }).click(); await idle();
  const view = await inspect();
  const point = view.nodes.find(n => n.kind !== 'cluster' && n.screen.x > 460 && n.screen.x < 1250 && n.screen.y > 220 && n.screen.y < 650);
  assert.ok(point, 'A visible note is available');
  await page.mouse.move(point.screen.x, point.screen.y); await idle();
  const hovered = await inspect();
  const expected = new Set([point.id, ...view.edges.filter(e => e.source === point.id || e.target === point.id).flatMap(e => [e.source, e.target])]);
  check('Hover highlights exact graph neighbors', hovered.hover === point.id && hovered.highlighted.length === expected.size && hovered.highlighted.every(id => expected.has(id)));
  await page.mouse.down(); await page.mouse.move(point.screen.x + 45, point.screen.y + 25, { steps: 12 }); await page.mouse.up(); await idle();
  const dragged = (await inspect()).nodes.find(n => n.id === point.id);
  check('Dragging moves only selected node without restarting physics', Math.abs(dragged.x - point.x - 45 / view.camera.k) < 1 && (await inspect()).selected === null);
  const panStart = await inspect();
  await page.mouse.move(500, 820); await page.mouse.down(); await page.mouse.move(540, 845, { steps: 8 }); await page.mouse.up(); await idle();
  const panEnd = await inspect();
  check('Background pan follows pointer distance', Math.abs(panEnd.camera.x - panStart.camera.x + 40 / panStart.camera.k) < .01 && Math.abs(panEnd.camera.y - panStart.camera.y + 25 / panStart.camera.k) < .01);
  const beforeZoom = (await inspect()).camera, anchorCenter = (await inspect()).viewport;
  await page.mouse.move(900, 430); await page.mouse.wheel(0, -150); await idle();
  const afterZoom = (await inspect()).camera;
  check('Wheel zoom responds', afterZoom.k > beforeZoom.k);
  check('Wheel zoom preserves world position under pointer', Math.abs(beforeZoom.x + (900 - anchorCenter.x) / beforeZoom.k - afterZoom.x - (900 - anchorCenter.x) / afterZoom.k) < .01 && Math.abs(beforeZoom.y + (430 - anchorCenter.y) / beforeZoom.k - afterZoom.y - (430 - anchorCenter.y) / afterZoom.k) < .01);
  await page.locator('canvas.graph-canvas').focus(); await page.keyboard.press('Home'); await page.keyboard.press('Enter'); await idle();
  check('Keyboard opens a real entity', (await inspect()).selected !== null);
  await page.keyboard.press('Escape');
  await page.locator('canvas.graph-canvas').focus(); await page.keyboard.press('Home');
  const reachable = new Set();
  for (let i = 0; i < initial.nodes.length; i++) { reachable.add((await inspect()).hover); await page.keyboard.press('ArrowRight'); }
  check('Keyboard navigation reaches every graph node', reachable.size === initial.nodes.length && !reachable.has(null));
  await page.keyboard.press('r');
  check('Relationships accessible without a pointer', await page.locator('.graph-details').isVisible());
  await page.locator('.graph-details button').first().click();
  check('Relationship inspector explains source provenance', /Indexed group membership|galaxy\/build.py/.test(await page.locator('.graph-details').innerText()));
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Fit graph', exact: true }).click(); await idle();
  check('Reduced motion freezes after interaction', (await inspect()).reducedMotion && !(await inspect()).animating);
  await page.keyboard.press('Control+k'); check('Existing command palette remains available', await page.locator('#palette').isVisible()); await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 }); await page.getByRole('button', { name: 'Fit graph', exact: true }).click(); await idle();
  check('Mobile has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  check('Mobile toolbar does not cover group tabs', await page.evaluate(() => document.querySelector('.graph-tools').getBoundingClientRect().bottom < document.querySelector('.side').getBoundingClientRect().top));
  await page.screenshot({ path: `${out}/graph-mobile.png` });
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('button', { name: 'Fit graph', exact: true }).click(); await idle();
  // Measure browser rAF while actual pointer events drag a node and wheel zoom the full graph.
  await page.evaluate(() => { window.framesMeasured = []; let prev; const end = performance.now() + 2500; function sample(t) { if (prev) window.framesMeasured.push(t - prev); prev = t; if (t < end) requestAnimationFrame(sample); } requestAnimationFrame(sample); });
  const perfView = await inspect(), perfNode = perfView.nodes.find(n => n.screen.x > 470 && n.screen.x < 1200 && n.screen.y > 230 && n.screen.y < 630);
  await page.mouse.move(perfNode.screen.x, perfNode.screen.y); await page.mouse.down();
  for (let i = 0; i < 50; i++) await page.mouse.move(perfNode.screen.x + i, perfNode.screen.y + Math.sin(i / 10) * 20);
  await page.mouse.up();
  for (let i = 0; i < 20; i++) { await page.mouse.wheel(0, i % 2 ? 15 : -15); await page.waitForTimeout(40); }
  await page.waitForTimeout(2600);
  const frames = await page.evaluate(() => window.framesMeasured);
  frames.sort((a, b) => a - b);
  results.frames = { samples: frames.length, medianMs: frames[Math.floor(frames.length * .5)], p95Ms: frames[Math.floor(frames.length * .95)], maxMs: frames.at(-1) };
  check('Local drag/zoom frame budget near 60fps', results.frames.p95Ms < 20);
  await page.goto(`${base}/?view=galaxy&mute=1`);
  await page.waitForFunction(() => window.galaxy && !document.body.classList.contains('booting'), { timeout: 60000 });
  check('Galaxy fallback boots with real nodes', await page.evaluate(() => window.galaxy.graphData().nodes.length) === sourceContext.source.nodes.length);
  results.resources.galaxy = await page.evaluate(() => performance.getEntriesByType('resource').map(e => ({ name: e.name, bytes: e.encodedBodySize, transferred: e.transferSize })));
  await page.screenshot({ path: `${out}/galaxy-fallback.png` });
  check('No browser runtime errors', results.errors.length === 0);
} catch (error) {
  results.failure = error.stack;
  await page.screenshot({ path: `${out}/failure.png` });
  process.exitCode = 1;
} finally {
  await writeFile(`${out}/browser-results.json`, JSON.stringify(results, null, 2));
  console.log(JSON.stringify({ ...results, resources: undefined }, null, 2));
  await browser.close();
}
