export const renderDawAgentMarkdown = (spec: DawAgentSpecInput): string => {
  const fmLines = [
    '---',
    `schema: "xyp3rn.agent/v3"`,
    `id: "agent-${spec.name}"`,
    `type: agent`,
    `title: "${spec.title}"`,
    `name: "${spec.name}"`,
    `class: "${spec.class}"`,
    `domain: "${spec.domain}"`,
    `sector: "04_AGENTS"`,
    `status: active`,
    `version: 1`,
    `model: "${spec.model}"`,
    `capabilities: [${spec.capabilities.join(', ')}]`,
    `tools: [${spec.tools.join(', ')}]`,
    `provenance: "phase15://daw-agent-catalog/${spec.name}"`,
    `tags: [xyp3rn, os3, daw-brain, agent]`,
    '---',
  ];

  const bodyLines = [
    '',
    '## Role',
    spec.role,
    '',
    '## Responsibilities',
    spec.responsibilities,
    ...(spec.consolidates && spec.consolidates.length > 0
      ? ['', `Consolidated proposed roles: ${spec.consolidates.join(', ')}.`]
      : []),
    '',
    '## Context Requirements',
    spec.contextRequirements,
    '',
    '## Contract',
    `- **Inputs:** ${spec.inputs}`,
    `- **Outputs:** ${spec.outputs}`,
    `- **Reads:** ${spec.readPermissions}`,
    `- **Writes:** ${spec.writePermissions}`,
    '',
    '## Procedure',
    spec.procedure,
    '',
    '## Constraints',
    spec.constraints,
    '',
    '## Refuses',
    spec.refuses,
    '',
    '## Escalation',
    spec.escalation,
    '',
    '## Evaluation Criteria',
    spec.evaluationCriteria,
    '',
  ];

  return [...fmLines, ...bodyLines].join('\n');
};

export const writeDawAgentDefinitionsToDir = (targetDir: string): readonly string[] => {
  fs.mkdirSync(targetDir, { recursive: true });
  const written: string[] = [];
  for (const spec of DAW_AGENT_CATALOG) {
    const filePath = path.join(targetDir, `${spec.name}.md`);
    fs.writeFileSync(filePath, renderDawAgentMarkdown(spec), 'utf8');
    written.push(filePath);
  }
  return written;
};
